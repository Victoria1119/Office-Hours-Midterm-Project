# make_prolog.py
# Reads the two input files (faculty.txt, classes.txt) and the office hours
# made by the C program (schedule_data.txt), then writes schedule.pl:
# a Prolog file with FACTS (what is true) and RULES (how to figure things out).
#
# Run:  python3 make_prolog.py

DAY_NAMES = ["monday", "tuesday", "wednesday", "thursday", "friday"]


def q(text):
    """Puts text in single quotes so Prolog treats it as one value.
    'Dr.Thomas' and 'Data and Algorithms' need quotes because of the
    capital letters, dots and spaces."""
    return "'" + text.strip().replace("'", "\\'") + "'"


facts = []

# ---------- faculty.txt ----------
# Dr.Thomas|Computer Science|COSC208, COSC214|4|CS201
with open("faculty.txt") as f:
    for line in f:
        parts = line.strip().split("|")
        if len(parts) < 4:
            continue                          # skip blank or bad lines
        name, dept, courses, hours = parts[0], parts[1], parts[2], parts[3]
        office = parts[4] if len(parts) > 4 else "TBA"
        facts.append(f"professor({q(name)}, {q(dept)}, {q(office)}).")
        facts.append(f"hours_needed({q(name)}, {hours.strip()}).")
        for code in courses.split(","):
            facts.append(f"teaches({q(name)}, {q(code)}).")

# ---------- classes.txt ----------
# COSC214|Data and Algorithms|Dr.Thomas|M-W--|11:00AM|1:15PM|CS330
with open("classes.txt") as f:
    for line in f:
        parts = line.strip().split("|")
        if len(parts) < 7:
            continue
        code, title, prof, days, start, end, room = parts
        facts.append(f"course({q(code)}, {q(title)}, {q(room)}).")
        # one meets/4 fact for each day the class meets
        for i, letter in enumerate(days):
            if letter != "-" and i < 5:
                facts.append(f"meets({q(code)}, {DAY_NAMES[i]}, {q(start)}, {q(end)}).")

# ---------- schedule_data.txt (office hours from the C program) ----------
# Dr.Thomas|Computer Science|OFFICE|Monday & Wednesday|1:15 PM to 3:15 PM|CS201
with open("schedule_data.txt") as f:
    for line in f:
        parts = line.strip().split("|")
        if len(parts) < 6 or parts[2] != "OFFICE":
            continue
        name, days, times = parts[0], parts[3], parts[4]
        start, end = times.split(" to ")
        for day in days.split(" & "):
            facts.append(f"office_hours({q(name)}, {day.lower()}, {q(start)}, {q(end)}).")

# Prolog wants all facts of the same kind next to each other,
# so sort them (this groups all course(...) facts, all meets(...) facts, etc.)
facts.sort()

# ---------- rules ----------
rules = """
% Who teaches a course?
taught_by(Course, Prof) :- teaches(Prof, Course).

% Which professors have office hours on a given day?
office_hours_on(Day, Prof, Start, End) :- office_hours(Prof, Day, Start, End).

% Does a professor teach on a given day?
teaches_on(Prof, Day) :- teaches(Prof, Course), meets(Course, Day, _, _).

% Where does a course meet?
room_of(Course, Room) :- course(Course, _, Room).

% Where are a professor's office hours held?
office_of(Prof, Office) :- professor(Prof, _, Office).

% Which professors are in the same department?
same_department(P1, P2) :- professor(P1, Dept, _), professor(P2, Dept, _), P1 \\= P2.
"""

with open("schedule.pl", "w") as f:
    f.write("% schedule.pl - generated by make_prolog.py. Do not edit by hand.\n")
    f.write("\n")
    f.write("% ---------- FACTS ----------\n")
    f.write("\n".join(facts) + "\n")
    f.write("\n% ---------- RULES ----------")
    f.write(rules)

print(f"Created schedule.pl with {len(facts)} facts")
